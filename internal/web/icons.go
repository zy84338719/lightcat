// icon 返回装饰性内联 SVG。返回 template.HTML：内容由本文件全额控制，
// 不经过转义是刻意的（模板里插进 <a>/<h2>/<div> 都能当元素用）。
func icon(name string) template.HTML {
	body, ok := svgIcons[name]
	if !ok {
		return ""
	}
	return template.HTML(`<svg class="icon" aria-hidden="true" focusable="false" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">` + body + `</svg>`)
}
